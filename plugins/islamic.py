import random
from config import PREFIX

AYAT = [
    "﴿ فَإِنَّ مَعَ الْعُسْرِ يُسْرًا ۝ إِنَّ مَعَ الْعُسْرِ يُسْرًا ﴾ [الشرح: 5-6]",
    "﴿ وَلَسَوْفَ يُعْطِيكَ رَبُّكَ فَتَرْضَىٰ ﴾ [الضحى: 5]",
    "﴿ لَا يُكَلِّفُ اللَّهُ نَفْسًا إِلَّا وُسْعَهَا ﴾ [البقرة: 286]",
    "﴿ وَاصْبِرْ لِحُكْمِ رَبِّكَ فَإِنَّكَ بِأَعْيُنِنَا ﴾ [الطور: 48]"
]

ADHKAR = [
    "سُبْحَانَ اللَّهِ وَبِحَمْدِهِ ، سُبْحَانَ اللَّهِ الْعَظِيمِ.",
    "لَا إِلَهَ إِلَّا أَنْتَ سُبْحَانَكَ إِنِّي كُنْتُ مِنَ الظَّالِمِينَ.",
    "اللَّهُمَّ صَلِّ وَسَلِّمْ عَلَى نَبِيِّنَا مُحَمَّدٍ.",
    "أَسْتَغْفِرُ اللَّهَ الْعَظِيمَ الَّذِي لَا إِلَهَ إِلَّا هُوَ الْحَيُّ الْقَيُّومُ وَأَتُوبُ إِلَيْهِ."
]

DUAS = [
    "اللهم إني أسألك الهدى والتقى والعفاف والغنى.",
    "ربنا آتنا في الدنيا حسنة وفي الآخرة حسنة وقنا عذاب النار.",
    "اللهم اشرح صدورنا ويسر أمورنا واغفر ذنوبنا."
]

def handle_islamic(text):
    if text == f"{PREFIX}اية":
        return f"📖 *آية كريمة:*\n\n{random.choice(AYAT)}"
    elif text in [f"{PREFIX}اذكار", f"{PREFIX}صباح", f"{PREFIX}مساء", f"{PREFIX}تسبيح"]:
        return f"📿 *ذكر:*\n\n{random.choice(ADHKAR)}"
    elif text == f"{PREFIX}دعاء":
        return f"🤲 *دعاء:*\n\n{random.choice(DUAS)}"
    elif text == f"{PREFIX}حديث":
        return "🌙 *حديث شريف:*\nقال رسول الله ﷺ: «الكَلِمَةُ الطَّيِّبَةُ صَدَقَةٌ»."
    return None
